// Writes supabase/seeds/10_districts_osm.sql and 20_venues_osm.sql from fetched Overpass data.
// Output is deterministic for the same input (no wall-clock timestamps), so re-runs are diffable.
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { FetchAllResult } from './fetch-all.ts';
import type { FetchedQuery } from './overpass.ts';
import { buildDistricts } from './build-districts.ts';
import { buildVenues, type VenueRow } from './build-venues.ts';
import { bool, coord, lit, osmVenueId } from './sql.ts';
import { WARSAW_AREA_ID } from './queries.ts';

const BATCH = 500;

function header(title: string, queries: FetchedQuery[], extra: string[]): string {
  const ts = queries.map(
    (q) =>
      `--   ${q.name.padEnd(15)} osm_base=${q.response.osm3s?.timestamp_osm_base}  endpoint=${new URL(q.endpoint).host}  query_sha256=${q.queryHash}`,
  );
  return [
    '-- =============================================================================',
    `-- ${title}`,
    '-- GENERATED by scripts/osm (npm run osm:import). DO NOT EDIT BY HAND.',
    '--',
    '-- Data © OpenStreetMap contributors, licensed under the Open Database License (ODbL) 1.0.',
    '--   https://www.openstreetmap.org/copyright',
    '--   https://opendatacommons.org/licenses/odbl/1-0/',
    '-- The rows below are a Derivative Database of OpenStreetMap and remain under ODbL.',
    '--',
    `-- Source: Overpass API, area ${WARSAW_AREA_ID} (relation 336075, Warszawa, admin_level 6).`,
    '-- Overpass data timestamps / endpoints / query hashes:',
    ...ts,
    ...extra.map((l) => `-- ${l}`),
    '-- =============================================================================',
    '',
  ].join('\n');
}

function maxOsmBase(queries: FetchedQuery[]): string {
  return (
    queries
      .map((q) => q.response.osm3s?.timestamp_osm_base ?? '')
      .sort()
      .at(-1) ?? new Date(0).toISOString()
  );
}

function venueValues(r: VenueRow, importedAt: string): string {
  return (
    `(${lit(r.id)}, ${lit(r.name)}, ${lit(r.kind)}, 'SRID=4326;POINT(${coord(r.lng)} ${coord(r.lat)})', ` +
    `${lit(r.address)}, ${lit(r.surface)}, ${bool(r.isLit)}, ${bool(r.isFree)}, ${bool(r.isIndoor)}, ` +
    `${lit(r.access)}, ${lit(r.openingHours)}, ${lit(r.website)}, ${lit(r.phone)}, 'osm', ${lit(r.osmType)}, ${r.osmId}, ` +
    `${lit(JSON.stringify(r.osmTags))}::jsonb, ${lit(importedAt)}::timestamptz, ${r.hidden ? "'hidden'" : "'active'"})`
  );
}

const KEEP_IF_EDITED = [
  'name',
  'kind',
  'address',
  'surface',
  'is_lit',
  'is_free',
  'is_indoor',
  'access',
  'opening_hours',
  'website',
  'phone',
];

function venuesSql(rows: VenueRow[], importedAt: string): string {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += BATCH) {
    const chunk = rows.slice(i, i + BATCH);
    out.push(
      `insert into public.venues as v (id, name, kind, location, address, surface, is_lit, is_free, is_indoor, access,\n` +
        `  opening_hours, website, phone, source, osm_type, osm_id, osm_tags, osm_imported_at, status)\nvalues\n` +
        chunk.map((r) => '  ' + venueValues(r, importedAt)).join(',\n') +
        `\non conflict on constraint venues_osm_uniq do update set\n` +
        `  location = excluded.location,\n  osm_tags = excluded.osm_tags,\n  osm_imported_at = excluded.osm_imported_at,\n` +
        KEEP_IF_EDITED.map(
          (c) =>
            `  ${c} = case when v.locally_edited_at is null then excluded.${c} else v.${c} end`,
        ).join(',\n') +
        ';\n',
    );
    const vs = chunk.flatMap((r) =>
      r.sports.map((s) => `(${lit(r.id)}::uuid, ${lit(s.sport)}, ${bool(s.inferred)})`),
    );
    out.push(
      `with src(venue_id, sport_id, inferred) as (values\n  ${vs.join(',\n  ')}\n),\n` +
        `stale as (\n  delete from public.venue_sports vs using public.venues v\n` +
        `   where v.id = vs.venue_id and v.locally_edited_at is null\n` +
        `     and vs.venue_id in (select distinct s.venue_id from src s)\n` +
        `     and not exists (select 1 from src s where s.venue_id = vs.venue_id and s.sport_id = vs.sport_id))\n` +
        `insert into public.venue_sports (venue_id, sport_id, inferred)\n` +
        `select s.venue_id, s.sport_id, s.inferred from src s join public.venues v on v.id = s.venue_id\n` +
        ` where v.locally_edited_at is null\n` +
        `on conflict (venue_id, sport_id) do update set inferred = excluded.inferred;\n`,
    );
  }
  out.push(
    `-- OSM objects that disappeared since an earlier import: soft-delete (events may reference them).\n` +
      `update public.venues v set status = 'hidden'\n` +
      ` where v.source = 'osm' and v.status = 'active' and v.locally_edited_at is null\n` +
      `   and v.osm_imported_at < ${lit(importedAt)}::timestamptz;\n`,
  );
  return out.join('\n');
}

async function previousCounts(file: string): Promise<Record<string, number> | null> {
  if (!existsSync(file)) return null;
  const text = await readFile(file, 'utf8');
  const m = /^-- counts: (\{.*\})$/m.exec(text);
  if (!m) return null;
  try {
    return JSON.parse(m[1]!) as Record<string, number>;
  } catch {
    return null;
  }
}

export async function build(
  fetched: FetchAllResult,
  opts: { root: string; force: boolean; log: (m: string) => void },
) {
  const { log } = opts;
  const seedsDir = join(opts.root, '..', '..', 'supabase', 'seeds');
  const venueFile = join(seedsDir, '20_venues_osm.sql');
  const districtFile = join(seedsDir, '10_districts_osm.sql');

  // ---- districts
  const d = buildDistricts(fetched.districts);
  log(
    `Districts: ${d.areaCheck}; matched ${d.matched.length}/18${d.missing.length ? `, missing: ${d.missing.join(', ')}` : ''}`,
  );
  const dSql =
    header(
      'Bojo — Warsaw district (dzielnica) boundaries from OpenStreetMap.',
      [fetched.districts],
      [
        `Polygons are assembled by PostGIS (ST_BuildArea over member ways), simplified with`,
        `ST_SimplifyPreserveTopology(tolerance 0.0001°). Districts without a boundary keep using their centre.`,
        `Overpass area check: ${d.areaCheck}`,
        `counts: ${JSON.stringify({ districts: d.matched.length })}`,
      ],
    ) + d.statements.join('\n');

  // ---- venues
  const venueQs = ['pitches', 'swimming', 'workout', 'running', 'sports_centres', 'containers'].map(
    (n) => fetched.venues[n]!,
  );
  const { rows, stats } = buildVenues(fetched.venues);
  for (const r of rows) r.id = osmVenueId(r.osmType, r.osmId);
  const importedAt = maxOsmBase(venueQs);
  const counts: Record<string, number> = { total: rows.length, ...stats.byKind };

  const prev = await previousCounts(venueFile);
  if (prev && !opts.force) {
    for (const [k, n] of Object.entries(prev)) {
      const now = counts[k] ?? 0;
      if (n >= 20 && now < n * 0.8) {
        throw new Error(
          `count for "${k}" dropped from ${n} to ${now} (>20%). Aborting; re-run with --force if this is expected.`,
        );
      }
    }
  }

  const vSql =
    header('Bojo — sports venues of Warszawa from OpenStreetMap.', venueQs, [
      `Rules: docs/OSM_IMPORT.md (normalization, exclusions, grouping). Ids: uuid v5 of 'osm/<type>/<id>'.`,
      `Upsert by (osm_type, osm_id); rows with locally_edited_at keep their attributes (only location/tags refresh).`,
      `osm_imported_at = newest Overpass osm_base timestamp (${importedAt}).`,
      `counts: ${JSON.stringify(counts)}`,
      `sports: ${JSON.stringify(stats.bySport)}`,
    ]) + (rows.length ? venuesSql(rows, importedAt) : '');

  await writeFile(districtFile, dSql);
  await writeFile(venueFile, vSql);
  log(`Wrote ${districtFile}`);
  log(`Wrote ${venueFile}`);
  log('Venue stats:\n' + JSON.stringify(stats, null, 2));
}
